def main():
    parser = argparse.ArgumentParser(
        description="Verify XUnity translations against DeepL.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--input-dir", type=Path,
        default=Path(__file__).parent.parent.parent / "BepInEx" / "Translation" / "en" / "Text",
        help="Directory containing the .txt translation files",
    )
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).parent / "deepl_verification_report.tsv",
        help="Where to save the TSV divergence report",
    )
    parser.add_argument("--threshold",  type=float, default=0.4)
    parser.add_argument("--limit",      type=int,   default=None)
    parser.add_argument("--files",      nargs="+",  default=TRANSLATION_FILES)
    parser.add_argument("--include-short",       action="store_true")
    parser.add_argument("--include-passthrough", action="store_true")
    parser.add_argument("--no-ui", action="store_true",
                        help="Skip the review UI, just generate the TSV report.")
    parser.add_argument(
        "--glossary", type=Path,
        default=Path(__file__).parent / "deepl_glossary.tsv",
        help="Path to the glossary TSV file (default: deepl_glossary.tsv next to this script)",
    )
    parser.add_argument(
        "--refresh-glossary", action="store_true",
        help="Force re-upload of the glossary to DeepL, ignoring the cached ID.",
    )

    args = parser.parse_args()

    # Load .env from project root
    _env_file = Path(__file__).parent.parent.parent / ".env"
    if _env_file.exists():
        try:
            from dotenv import load_dotenv
            load_dotenv(_env_file, override=False)
        except ImportError:
            with open(_env_file, "r", encoding="utf-8") as _f:
                for _line in _f:
                    _line = _line.strip()
                    if not _line or _line.startswith("#") or "=" not in _line:
                        continue
                    _k, _, _v = _line.partition("=")
                    _k = _k.strip()
                    _v = _v.strip().strip('"').strip("'")
                    if _k and _k not in os.environ:
                        os.environ[_k] = _v

    api_key = os.environ.get("DEEPL_API_KEY", "").strip()
    if not api_key:
        print("ERROR: DEEPL_API_KEY not set.")
        print(f"Add it to {_env_file}:  DEEPL_API_KEY=\"your-key:fx\"")
        sys.exit(1)

    if not all(Path(f).is_absolute() for f in args.files):
        if not args.input_dir.exists():
            print(f"ERROR: input directory not found: {args.input_dir}")
            sys.exit(1)

    flagged = verify_files(
        input_dir=args.input_dir,
        output_path=args.output,
        api_key=api_key,
        files=args.files,
        threshold=args.threshold,
        limit=args.limit,
        skip_short=not args.include_short,
        glossary_path=args.glossary,
        refresh_glossary=args.refresh_glossary,
        skip_tagged_passthrough=not args.include_passthrough,
    )

    if flagged and not args.no_ui:
        print(f"\nLaunching review UI for {len(flagged)} flagged entries...")
        launch_review_ui(flagged, args.input_dir)
    elif flagged:
        print(f"\n{len(flagged)} entries flagged. See {args.output}")


if __name__ == "__main__":
    main()
