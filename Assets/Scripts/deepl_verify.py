def launch_review_ui(flagged: list[dict], input_dir: Path):
    """
    One-at-a-time review UI.  Two buttons advance automatically;
    a preview shows the exact line that will be written to the file.
    """
    try:
        import tkinter as tk
        from tkinter import messagebox
    except ImportError:
        print("tkinter not available — skipping UI.  Use the TSV report instead.")
        return

    DARK   = "#1e1e1e"
    PANEL  = "#2d2d2d"
    ACCENT = "#569cd6"
    FG     = "#d4d4d4"
    GREEN  = "#4ec9b0"
    ORANGE = "#ce9178"
    DIM    = "#6a6a6a"

    root = tk.Tk()
    root.title("Translation Review")
    root.geometry("900x640")
    root.configure(bg=DARK)
    root.resizable(True, True)

    # ── State ─────────────────────────────────────────────────
    choices  = {}          # idx -> 'existing' | 'deepl'
    current  = [0]         # mutable pointer
    total    = len(flagged)

    # ── Helpers ───────────────────────────────────────────────
    def lbl(parent, text, color=DIM, size=9, bold=False):
        f = ("Consolas", size, "bold") if bold else ("Consolas", size)
        tk.Label(parent, text=text, bg=PANEL, fg=color, font=f,
                 anchor="w").pack(fill=tk.X, padx=12, pady=(8, 0))

    def txtbox(parent, height, color=FG):
        t = tk.Text(parent, height=height, bg="#141414", fg=color,
                    font=("Consolas", 10), wrap=tk.WORD, relief=tk.FLAT,
                    state=tk.DISABLED, padx=6, pady=4)
        t.pack(fill=tk.X, padx=12, pady=(2, 0))
        return t

    def set_txt(widget, text, color=None):
        widget.configure(state=tk.NORMAL)
        if color:
            widget.configure(fg=color)
        widget.delete("1.0", tk.END)
        widget.insert(tk.END, text)
        widget.configure(state=tk.DISABLED)

    # ── Header ────────────────────────────────────────────────
    header = tk.Frame(root, bg=DARK)
    header.pack(fill=tk.X, padx=12, pady=(10, 0))

    progress_lbl = tk.Label(header, text="", bg=DARK, fg=ACCENT,
                            font=("Consolas", 10, "bold"))
    progress_lbl.pack(side=tk.LEFT)

    file_lbl = tk.Label(header, text="", bg=DARK, fg=DIM,
                        font=("Consolas", 9))
    file_lbl.pack(side=tk.RIGHT)

    # Progress bar (canvas)
    bar_canvas = tk.Canvas(root, height=4, bg="#333333",
                           highlightthickness=0)
    bar_canvas.pack(fill=tk.X, padx=12, pady=(4, 0))
    bar_fill = bar_canvas.create_rectangle(0, 0, 0, 4, fill=ACCENT, width=0)

    def update_bar(idx):
        bar_canvas.update_idletasks()
        w = bar_canvas.winfo_width()
        x = int(w * (idx / total)) if total else 0
        bar_canvas.coords(bar_fill, 0, 0, x, 4)

    # ── Content panel ─────────────────────────────────────────
    panel = tk.Frame(root, bg=PANEL)
    panel.pack(fill=tk.BOTH, expand=True, padx=12, pady=8)

    lbl(panel, "JAPANESE",          ACCENT, bold=True)
    txt_jp  = txtbox(panel, 2)

    lbl(panel, "CURRENT TRANSLATION", ORANGE, bold=True)
    txt_cur = txtbox(panel, 2, ORANGE)

    lbl(panel, "DEEPL TRANSLATION",   GREEN,  bold=True)
    txt_dl  = txtbox(panel, 2, GREEN)

    lbl(panel, "PREVIEW  —  line as it will appear in the file", DIM)
    txt_pre = txtbox(panel, 3, FG)

    # ── Button row ────────────────────────────────────────────
    btn_row = tk.Frame(root, bg=DARK)
    btn_row.pack(fill=tk.X, padx=12, pady=(0, 10))

    BTN = dict(font=("Consolas", 12, "bold"), relief=tk.FLAT,
               cursor="hand2", padx=20, pady=10)

    btn_keep  = tk.Button(btn_row, text="◀  Keep existing",
                          bg="#3a2800", fg=ORANGE, **BTN)
    btn_deepl = tk.Button(btn_row, text="Use DeepL  ▶",
                          bg="#003a28", fg=GREEN,  **BTN)
    btn_keep .pack(side=tk.LEFT,  expand=True, fill=tk.X, padx=(0, 4))
    btn_deepl.pack(side=tk.RIGHT, expand=True, fill=tk.X, padx=(4, 0))

    # ── Summary / apply screen ────────────────────────────────
    def show_summary():
        # Destroy content and show summary
        for w in panel.winfo_children():
            w.destroy()
        for w in btn_row.winfo_children():
            w.destroy()
        header.pack_forget()
        bar_canvas.pack_forget()

        deepl_count = sum(1 for c in choices.values() if c == "deepl")
        tk.Label(panel, text="Review complete",
                 bg=PANEL, fg=ACCENT,
                 font=("Consolas", 14, "bold")).pack(pady=(30, 8))
        tk.Label(panel,
                 text=f"{deepl_count} entries will be replaced with DeepL translations\n"
                      f"{total - deepl_count} entries kept as existing",
                 bg=PANEL, fg=FG, font=("Consolas", 11)).pack(pady=8)

        def do_apply():
            to_patch = []
            for i, e in enumerate(flagged):
                if choices.get(i) == "deepl":
                    new_val = reapply_tags(
                        e['escaped_value'], e['value_stripped'], e['deepl_en'])
                    to_patch.append({
                        'fname':             e['fname'],
                        'original_line':     e['original_line'],
                        'new_escaped_value': new_val,
                    })
            if not to_patch:
                messagebox.showinfo("Nothing to do",
                                    "No entries were set to 'Use DeepL'.")
                return
            apply_changes(input_dir, to_patch)
            messagebox.showinfo("Done",
                f"Applied {len(to_patch)} changes.\nOriginal files backed up as .bak")
            root.destroy()

        tk.Button(panel, text="Apply Changes", bg=ACCENT, fg="#ffffff",
                  font=("Consolas", 12, "bold"), relief=tk.FLAT,
                  padx=24, pady=10, command=do_apply).pack(pady=16)
        tk.Button(panel, text="Cancel (no changes)", bg="#333333", fg=DIM,
                  font=("Consolas", 10), relief=tk.FLAT,
                  command=root.destroy).pack()

    # ── Load entry ────────────────────────────────────────────
    def load(idx):
        if idx >= total:
            show_summary()
            return
        e = flagged[idx]
        progress_lbl.config(text=f"Entry {idx + 1} of {total}")
        file_lbl.config(text=Path(e['fname']).name +
                        f"  ·  sim {e['similarity']:.2f}")
        update_bar(idx)

        set_txt(txt_jp,  e['key_stripped'])
        set_txt(txt_cur, e['value_stripped'], ORANGE)
        set_txt(txt_dl,  e['deepl_en'],       GREEN)

        # Preview: show the full .txt line for each option
        new_val      = reapply_tags(e['escaped_value'], e['value_stripped'], e['deepl_en'])
        orig_m       = re.search(r'(?<!\\)=', e['original_line'])
        key_part     = e['original_line'][:orig_m.end()] if orig_m else ""
        preview_line = key_part + new_val
        set_txt(txt_pre, preview_line, FG)

    def choose(decision):
        idx = current[0]
        choices[idx] = decision
        current[0]  += 1
        load(current[0])

    btn_keep .config(command=lambda: choose("existing"))
    btn_deepl.config(command=lambda: choose("deepl"))

    # Keyboard shortcuts
    root.bind("<Left>",  lambda _: choose("existing"))
    root.bind("<Right>", lambda _: choose("deepl"))

    load(0)
    root.mainloop()

    root.mainloop()


