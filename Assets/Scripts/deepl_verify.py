def verify_files(
    input_dir: Path,
    output_path: Path,
    api_key: str,
    files: list[str],
    threshold: float,
    limit: int | None,
    skip_short: bool,
    skip_tagged_passthrough: bool,
    glossary_path: Path | None = None,
    refresh_glossary: bool = False,
) -> list[dict]:
    # Cache lives in the current working directory
    cache_path = Path.cwd() / CACHE_FILE
    cache = load_cache(cache_path)
    print(f"Loaded cache: {len(cache)} entries  ({cache_path})")

    client = DeepLClient(api_key)
    try:
        usage = client.get_usage()
        used  = usage.get("character_count", 0)
        cap   = usage.get("character_limit", 500_000)
        print(f"DeepL usage: {used:,} / {cap:,} chars ({100*used/max(cap,1):.1f}%)")
    except Exception as e:
        print(f"Warning: could not fetch usage: {e}")

    # Set up glossary if provided
    glossary_id: str | None = None
    if glossary_path and glossary_path.exists():
        print(f"Glossary: {glossary_path.name}")
        try:
            glossary_id = client.ensure_glossary(glossary_path, force=refresh_glossary)
        except Exception as e:
            print(f"Warning: could not set up glossary: {e}")

    # Collect entries
    # tuple: (fname, key, value, stripped_key, stripped_value, original_line, escaped_value)
    all_entries = []
    for fname in files:
        p = Path(fname) if Path(fname).is_absolute() else input_dir / fname
        if not p.exists():
            print(f"  SKIP (missing): {fname}")
            continue
        file_entries = list(parse_entries(p))
        if limit:
            file_entries = file_entries[:limit]
        for key, value, original_line, escaped_value in file_entries:
            if not re.search(r'[぀-ゟ゠-ヿ一-鿿]', key):
                continue
            stripped_key   = strip_formatting_tags(key)
            stripped_value = strip_formatting_tags(value)
            if skip_short and len(stripped_key) < 3:
                continue
            if skip_tagged_passthrough and re.search(
                    r'[぀-ゟ゠-ヿ一-鿿]', stripped_value):
                continue
            all_entries.append((fname, key, value, stripped_key,
                                stripped_value, original_line, escaped_value))

    print(f"\n{len(all_entries)} entries to verify across {len(files)} file(s)")

    # Translate uncached
    uncached = list(dict.fromkeys(
        e[3] for e in all_entries if e[3] not in cache
    ))
    est = sum(len(k) for k in uncached)
    print(f"Need to translate {len(uncached)} new strings (~{est:,} chars)")

    if uncached:
        if input(f"Proceed with DeepL calls? [y/N] ").strip().lower() != 'y':
            print("Aborted.")
            return []

    for i in range(0, len(uncached), BATCH_SIZE):
        batch = uncached[i:i + BATCH_SIZE]
        n_batches = (len(uncached) + BATCH_SIZE - 1) // BATCH_SIZE
        print(f"  Batch {i//BATCH_SIZE + 1}/{n_batches} ({len(batch)} strings)...",
              end='', flush=True)
        try:
            translations = client.translate_batch(batch, glossary_id=glossary_id)
            for jp, en in zip(batch, translations):
                cache[jp] = en
            print(" ✓")
        except Exception as e:
            print(f" ✗ ({e})")
            save_cache(cache, cache_path)
            raise
        save_cache(cache, cache_path)
        time.sleep(0.5)

    print(f"\nCache now has {len(cache)} entries")

    # Compare, auto-accept keyword matches, and collect flagged entries
    flagged: list[dict] = []
    auto_patch: list[dict] = []

    def _is_auto_accept(deepl_en: str) -> bool:
        low = deepl_en.lower()
        return any(kw in low for kw in AUTO_ACCEPT_KEYWORDS)

    print(f"\nWriting TSV report to {output_path}...")
    with open(output_path, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f, delimiter='\t', quoting=csv.QUOTE_MINIMAL)
        writer.writerow(["File", "Sim", "Japanese", "Current", "DeepL", "Auto-accepted"])
        for fname, key, value, sk, sv, orig_line, esc_val in all_entries:
            deepl_en = cache.get(sk)
            if not deepl_en:
                continue
            sim = jaccard(sv, deepl_en)
            if sim >= threshold:
                continue

            if _is_auto_accept(deepl_en):
                writer.writerow([fname, f"{sim:.2f}", sk, sv, deepl_en, "yes"])
                auto_patch.append({
                    'fname':             fname,
                    'original_line':     orig_line,
                    'new_escaped_value': reapply_tags(esc_val, sv, deepl_en),
                })
            else:
                writer.writerow([fname, f"{sim:.2f}", sk, sv, deepl_en, ""])
                flagged.append({
                    'fname':          fname,
                    'key_stripped':   sk,
                    'value_stripped': sv,
                    'escaped_value':  esc_val,
                    'deepl_en':       deepl_en,
                    'similarity':     sim,
                    'original_line':  orig_line,
                })

    if auto_patch:
        print(f"Auto-accepted {len(auto_patch)} entries (keyword match) — applying now…")
        apply_changes(input_dir, auto_patch)

    print(f"Flagged {len(flagged)} entries for manual review")
    print(f"DeepL chars used this session: {client.characters_used:,}")
    return flagged


