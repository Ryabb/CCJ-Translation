class DeepLClient:
    def __init__(self, api_key: str):
        self.api_key  = api_key
        self.endpoint = DEEPL_API_FREE if api_key.endswith(":fx") else DEEPL_API_PRO
        self.session  = requests.Session()
        self.session.headers.update({"Authorization": f"DeepL-Auth-Key {api_key}"})
        self.characters_used = 0

    @property
    def glossary_base(self) -> str:
        return self.endpoint.replace("/translate", "/glossaries")

    # ── Glossary management ───────────────────────────────────

    def _tsv_entries(self, tsv_path: Path) -> str:
        """Return TSV content with comment/blank lines stripped and duplicates removed."""
        seen_keys: set[str] = set()
        lines = []
        for line in tsv_path.read_text(encoding='utf-8').splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith('#'):
                continue
            key = stripped.split('\t', 1)[0]
            if key in seen_keys:
                continue
            seen_keys.add(key)
            lines.append(stripped)
        return '\n'.join(lines)

    def _tsv_hash(self, tsv_path: Path) -> str:
        import hashlib
        return hashlib.md5(
            self._tsv_entries(tsv_path).encode('utf-8')
        ).hexdigest()

    def _load_glossary_id(self) -> tuple[str, str] | None:
        """Return (glossary_id, tsv_hash) from the local cache, or None."""
        p = Path.cwd() / GLOSSARY_ID_FILE
        if not p.exists():
            return None
        parts = p.read_text(encoding='utf-8').strip().split('\t')
        return (parts[0], parts[1]) if len(parts) == 2 else None

    def _save_glossary_id(self, glossary_id: str, tsv_hash: str):
        (Path.cwd() / GLOSSARY_ID_FILE).write_text(
            f"{glossary_id}\t{tsv_hash}", encoding='utf-8')

    def _delete_glossary(self, glossary_id: str):
        r = self.session.delete(f"{self.glossary_base}/{glossary_id}", timeout=10)
        if r.status_code not in (200, 204, 404):
            r.raise_for_status()

    def _create_glossary(self, tsv_path: Path) -> str:
        """Upload glossary to DeepL and return the new glossary_id."""
        entries = self._tsv_entries(tsv_path)
        r = self.session.post(
            self.glossary_base,
            headers={"Content-Type": "application/json"},
            json={
                "name":           "CCJ-Translation",
                "source_lang":    "JA",
                "target_lang":    "EN",
                "entries":        entries,
                "entries_format": "tsv",
            },
            timeout=30,
        )
        if not r.ok:
            raise RuntimeError(
                f"Glossary upload failed ({r.status_code}): {r.text[:400]}"
            )
        glossary_id = r.json()["glossary_id"]
        print(f"  Glossary uploaded → id: {glossary_id}")
        return glossary_id

    def ensure_glossary(self, tsv_path: Path, force: bool = False) -> str:
        """
        Return a valid DeepL glossary_id for tsv_path.
        Re-uploads when the TSV content has changed or force=True.
        """
        current_hash = self._tsv_hash(tsv_path)
        cached = self._load_glossary_id()

        if cached:
            gid, stored_hash = cached
            if not force and stored_hash == current_hash:
                print(f"  Glossary unchanged — reusing id: {gid}")
                return gid
            print("  Glossary force-refresh." if force else "  Glossary changed — re-uploading…")
            self._delete_glossary(gid)

        gid = self._create_glossary(tsv_path)
        self._save_glossary_id(gid, current_hash)
        return gid

    # ── Translation ───────────────────────────────────────────

    def translate_batch(self, texts: list[str],
                        glossary_id: str | None = None) -> list[str]:
        if not texts:
            return []
        params = {
            "source_lang": "JA",
            "target_lang": "EN-US",
            "preserve_formatting": "1",
            "tag_handling": "html",
        }
        if glossary_id:
            params["glossary_id"] = glossary_id
        data = [("text", t) for t in texts]
        try:
            r = self.session.post(self.endpoint, params=params, data=data, timeout=30)
            r.raise_for_status()
        except requests.HTTPError as e:
            if r.status_code == 456:
                raise RuntimeError("DeepL quota exceeded for the month.") from e
            if r.status_code == 403:
                raise RuntimeError("DeepL API key rejected (403). Check the key.") from e
            if r.status_code == 429:
                time.sleep(5)
                r = self.session.post(self.endpoint, params=params, data=data, timeout=30)
                r.raise_for_status()
        import html as _html
        result = r.json()
        self.characters_used += sum(len(t) for t in texts)
        return [_html.unescape(item["text"]) for item in result["translations"]]

    def get_usage(self) -> dict:
        usage_url = self.endpoint.replace("/translate", "/usage")
        r = self.session.get(usage_url, timeout=10)
        r.raise_for_status()
        return r.json()


# ============================================================
# CACHE
# ============================================================

def load_cache(cache_path: Path) -> dict:
    cache = {}
    if not cache_path.exists():
        return cache
    with open(cache_path, 'r', encoding='utf-8') as f:
        for line in f:
            parts = line.rstrip('\n').split('\t', 1)
            if len(parts) == 2:
                cache[parts[0]] = parts[1]
    return cache


def save_cache(cache: dict, cache_path: Path):
    with open(cache_path, 'w', encoding='utf-8') as f:
        for jp, en in cache.items():
            jp_s = jp.replace('\t', ' ').replace('\n', ' ')
            en_s = en.replace('\t', ' ').replace('\n', ' ')
            f.write(f"{jp_s}\t{en_s}\n")


# ============================================================
# SIMILARITY
# ============================================================

def tokenize(s: str) -> set[str]:
    s = re.sub(r"[^\w\s']", ' ', s.lower())
    return {w for w in s.split() if len(w) >= 2}


def jaccard(a: str, b: str) -> float:
    ta, tb = tokenize(a), tokenize(b)
    if not ta and not tb:
        return 1.0
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / len(ta | tb)


