# ============================================================
# XUNITY PARSING HELPERS
# ============================================================

def unescape_xunity(s: str) -> str:
    return s.replace(r'\=', '=').replace(r'\\', '\\')


def strip_formatting_tags(s: str) -> str:
    s = re.sub(r'<sprite[^>]*>', '', s)
    s = re.sub(r'</?color[^>]*>', '', s)
    s = re.sub(r'</?size[^>]*>', '', s)
    s = re.sub(r'</?align[^>]*>', '', s)
    s = re.sub(r'<alpha[^>]*>', '', s)
    s = re.sub(r'<line-height[^>]*>', '', s)
    s = re.sub(r'<br/?>', ' ', s)
    s = s.replace(r'\n', ' ').replace(r'\r', ' ')
    return re.sub(r'\s+', ' ', s).strip()


def parse_entries(filepath: Path):
    """Yield (key, value, original_line, escaped_value) for each entry."""
    raw = filepath.read_bytes()
    if raw.startswith(b'\xef\xbb\xbf'):
        raw = raw[3:]
    text = raw.decode('utf-8')
    lines = text.split('\r\n') if '\r\n' in text else text.split('\n')
    for line in lines:
        if not line:
            continue
        m = re.search(r'(?<!\\)=', line)
        if not m:
            continue
        escaped_value = line[m.start() + 1:]
        key   = unescape_xunity(line[:m.start()])
        value = unescape_xunity(escaped_value)
        yield key, value, line, escaped_value


# ============================================================
# TAG RESTORATION
# ============================================================

def reapply_tags(escaped_value: str, stripped_value: str, deepl_en: str) -> str:
    """
    Substitute deepl_en into the tag structure of escaped_value, preserving
    color/sprite tags. Returns the new escaped value ready to write to file.
    """
    unescaped = unescape_xunity(escaped_value)

    # Simple case: plain text appears as a contiguous block inside the tags
    if stripped_value and stripped_value in unescaped:
        result = unescaped.replace(stripped_value, deepl_en, 1)
        return result.replace('=', r'\=')

    # Multi-segment case: text is split across several color tags.
    # Wrap the entire English text in any sprite prefix + the first color found.
    sprite_match = re.match(r'^(<sprite[^>]+>)', unescaped)
    first_color  = re.search(r'(<color=[^>]+>)', unescaped)
    prefix = sprite_match.group(1) if sprite_match else ''
    if first_color:
        result = f"{prefix}{first_color.group(1)}{deepl_en}</color>"
    else:
        result = f"{prefix}{deepl_en}"
    return result.replace('=', r'\=')


# ============================================================
# FILE PATCHING
# ============================================================

def apply_changes(input_dir: Path, changes: list[dict]):
    """
    Write chosen DeepL translations back to the source .txt files.
    Each change dict: {'fname', 'original_line', 'new_escaped_value'}
    """
    by_file: dict[str, list] = {}
    for ch in changes:
        by_file.setdefault(ch['fname'], []).append(ch)

    for fname, file_changes in by_file.items():
        p = Path(fname) if Path(fname).is_absolute() else input_dir / fname
        content = p.read_text(encoding='utf-8')

        # Backup original before touching it
        backup = p.with_suffix(p.suffix + '.bak')
        backup.write_text(content, encoding='utf-8')
        print(f"  Backup saved: {backup.name}")

        lines = content.splitlines(keepends=True)

        # Map original line (stripped of newline) -> replacement
        replacements = {}
        for ch in file_changes:
            orig = ch['original_line']
            m = re.search(r'(?<!\\)=', orig)
            if not m:
                continue
            new_line = orig[:m.start() + 1] + ch['new_escaped_value']
            if not new_line.endswith('\n'):
                new_line += '\n'
            replacements[orig.rstrip('\n\r')] = new_line

        new_lines = [
            replacements.get(ln.rstrip('\n\r'), ln)
            for ln in lines
        ]
        p.write_text(''.join(new_lines), encoding='utf-8')
        print(f"  Patched {len(file_changes)} entries in {p.name}")


